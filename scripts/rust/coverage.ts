/**
 * How far the package has moved into the Rust core (docs/RUST.md): every module of `src/` in its
 * state, read from the Rust headers alone, so the report is the same on every machine and needs
 * no recording.
 *
 * - switched: the TypeScript is a wrapper over the core (``//! Port of `src/x.ts`, switched.``);
 * - ported: the core answers it, the package still runs the TypeScript (``… at sha256:<hash>.``);
 * - stays TypeScript: by its nature (``//! The core's counterpart of `src/x.ts`, …`` or a port's
 *   interface in `src/ports/`);
 * - TypeScript: not moved yet.
 *
 *   bun scripts/rust/coverage.ts           write crates/agent-plugins/COVERAGE.md
 *   bun scripts/rust/coverage.ts --check   fail when it is not current
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(import.meta.dir, '..', '..');
const crate = join(root, 'crates', 'agent-plugins');
const report = join(crate, 'COVERAGE.md');

type State = 'switched' | 'ported' | 'stays TypeScript' | 'TypeScript';

const PORT = /^\/\/! Port of `(src\/[^`]+\.ts)`(, switched)?/u;
const COUNTERPART = /^\/\/! The core's counterpart of `(src\/[^`]+\.ts)`/u;

const files = (dir: string, ending: string): string[] =>
  readdirSync(dir, { recursive: true, encoding: 'utf8' })
    .filter((name) => name.endsWith(ending) && !name.endsWith('.d.ts'))
    .map((name) => join(dir, name));

/** Each source's state as the Rust headers say it. */
function states(): Map<string, State> {
  const found = new Map<string, State>();
  for (const file of files(join(crate, 'src'), '.rs')) {
    const first = readFileSync(file, 'utf8').split('\n', 1)[0] ?? '';
    const port = PORT.exec(first);
    if (port?.[1] !== undefined) found.set(port[1], port[2] === undefined ? 'ported' : 'switched');
    const counterpart = COUNTERPART.exec(first);
    if (counterpart?.[1] !== undefined) found.set(counterpart[1], 'stays TypeScript');
  }
  return found;
}

const lines = (file: string): number => readFileSync(file, 'utf8').split('\n').length;

function render(): string {
  const known = states();
  const tally = new Map<string, Map<State, { modules: number; lines: number }>>();
  for (const file of files(join(root, 'src'), '.ts').toSorted()) {
    const source = relative(root, file);
    const folder = source.split('/')[1] ?? '';
    const state: State =
      known.get(source) ??
      (folder === 'ports' || folder === 'wasm' ? 'stays TypeScript' : 'TypeScript');
    const byState = tally.get(folder) ?? new Map();
    const row = byState.get(state) ?? { modules: 0, lines: 0 };
    byState.set(state, { modules: row.modules + 1, lines: row.lines + lines(file) });
    tally.set(folder, byState);
  }
  const order: readonly State[] = ['switched', 'ported', 'stays TypeScript', 'TypeScript'];
  const cell = (row?: { modules: number; lines: number }): string =>
    row === undefined ? '' : `${row.modules} (${row.lines} lines)`;
  const total = new Map<State, { modules: number; lines: number }>();
  const rows = [...tally].map(([folder, byState]) => {
    for (const [state, row] of byState) {
      const sum = total.get(state) ?? { modules: 0, lines: 0 };
      total.set(state, { modules: sum.modules + row.modules, lines: sum.lines + row.lines });
    }
    return `| \`${folder}\` | ${order.map((state) => cell(byState.get(state))).join(' | ')} |`;
  });
  return [
    '# Rust coverage',
    '',
    'Generated by `bun scripts/rust/coverage.ts` from the Rust headers (docs/RUST.md); never edit.',
    'Lines are the TypeScript files as they are now: a switched module counts its wrapper.',
    '',
    `| Module | ${order.join(' | ')} |`,
    `| --- | ${order.map(() => '---').join(' | ')} |`,
    `| all | ${order.map((state) => cell(total.get(state))).join(' | ')} |`,
    ...rows,
    '',
  ].join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  if (readFileSync(report, 'utf8') !== text) {
    console.error('crates/agent-plugins/COVERAGE.md is not current: bun scripts/rust/coverage.ts');
    process.exit(1);
  }
} else {
  writeFileSync(report, text);
}
